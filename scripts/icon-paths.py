"""Turn the app's Nerd Font icons into SVG paths, each centered on its ink.

The icons used to be drawn as font text. Nerd Font glyphs are wider than
their monospace cell and placed differently each, and text snaps to pixel
rows, so they sat visibly off center in round and square badges. Drawing
the same outlines as SVG, framed on each glyph's own center, fixes that at
every size while keeping their look and size (one em of the font = 24 units).

Writes src/ui/icon-paths.generated.ts from src/ui/icon-names.json.

Usage (needs fonttools):
    python scripts/icon-paths.py <JetBrainsMonoNerdFont-Regular.ttf>
"""

import json
import sys
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
UNITS = 24


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    font = TTFont(sys.argv[1])
    names = json.loads((ROOT / "src/ui/icon-names.json").read_text("utf-8"))
    glyphs = font.getGlyphSet()
    em = font["head"].unitsPerEm
    scale = UNITS / em
    order = set(font.getGlyphOrder())
    paths = {}
    missing = []
    for key, name in names.items():
        if name not in order:
            missing.append(f"{key}: {name}")
            continue
        bounds = BoundsPen(glyphs)
        glyphs[name].draw(bounds)
        if not bounds.bounds:
            missing.append(f"{key}: {name} (empty)")
            continue
        x0, y0, x1, y1 = bounds.bounds
        cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
        svg = SVGPathPen(glyphs, ntos=lambda v: f"{round(v, 2):g}")
        # Font units are y-up; SVG is y-down. Center the ink at (12, 12).
        pen = TransformPen(
            svg, (scale, 0, 0, -scale, UNITS / 2 - cx * scale, UNITS / 2 + cy * scale)
        )
        glyphs[name].draw(pen)
        paths[key] = svg.getCommands()
    if missing:
        print("Unknown Nerd Font glyphs:\n  " + "\n  ".join(missing))
        return 1
    lines = [
        "// Generated by scripts/icon-paths.py from src/ui/icon-names.json. Do not edit.",
        "// Each icon's outline from the Nerd Font, centered in a 24 by 24 box.",
        "import type { IconName } from './icons.generated';",
        "",
        "export const ICON_PATHS: Record<IconName, string> = {",
    ]
    lines += [f"  {key}: '{d}'," for key, d in paths.items()]
    lines += ["};", ""]
    out = ROOT / "src/ui/icon-paths.generated.ts"
    out.write_text("\n".join(lines), "utf-8")
    print(f"{out.relative_to(ROOT)}  {len(paths)} icons, {out.stat().st_size // 1024} KiB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
