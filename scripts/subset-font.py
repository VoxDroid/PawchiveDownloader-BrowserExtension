"""Subset JetBrains Mono Nerd Font into the woff2 files the extension ships.

Keeps Latin, Greek and Cyrillic text plus exactly the Nerd Font icons listed
in src/ui/icon-names.json, and writes src/ui/icons.generated.ts mapping each
icon name to its codepoint. After adding an icon, also run
scripts/icon-paths.py: the interface draws icons from those outlines.

Usage (needs fonttools + brotli):
    python scripts/subset-font.py <dir-with-JetBrainsMonoNerdFont-*.ttf>

The Nerd Font release is https://github.com/ryanoasis/nerd-fonts/releases
(JetBrainsMono.zip). Font license: SIL Open Font License 1.1.
"""

import json
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
WEIGHTS = {"Regular": 400, "Medium": 500, "SemiBold": 600, "Bold": 700}
TEXT_RANGES = [
    (0x0020, 0x007E),
    (0x00A0, 0x024F),
    (0x0370, 0x03FF),
    (0x0400, 0x04FF),
    (0x1E00, 0x1EFF),
    (0x2000, 0x206F),
    (0x20A0, 0x20CF),
    (0x2100, 0x214F),
    (0x2190, 0x21FF),
    (0x2200, 0x22FF),
    (0x2500, 0x25FF),
]


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    src = Path(sys.argv[1])
    names = json.loads((ROOT / "src/ui/icon-names.json").read_text("utf-8"))

    cmap = TTFont(src / "JetBrainsMonoNerdFont-Regular.ttf").getBestCmap()
    by_glyph = {glyph: cp for cp, glyph in cmap.items()}
    icons = {}
    missing = []
    for key, glyph in names.items():
        cp = by_glyph.get(glyph)
        if cp is None:
            missing.append(f"{key}: {glyph}")
        else:
            icons[key] = cp
    if missing:
        print("Unknown Nerd Font glyphs:\n  " + "\n  ".join(missing))
        return 1

    unicodes = sorted(
        {cp for lo, hi in TEXT_RANGES for cp in range(lo, hi + 1)} | set(icons.values())
    )
    out_dir = ROOT / "public/fonts"
    out_dir.mkdir(parents=True, exist_ok=True)
    for style in WEIGHTS:
        options = subset.Options()
        options.flavor = "woff2"
        options.layout_features = ["*"]
        options.name_IDs = ["*"]
        options.notdef_outline = True
        font = TTFont(src / f"JetBrainsMonoNerdFont-{style}.ttf")
        subsetter = subset.Subsetter(options)
        subsetter.populate(unicodes=unicodes)
        subsetter.subset(font)
        target = out_dir / f"JetBrainsMonoNerdFont-{style}.woff2"
        font.flavor = "woff2"
        font.save(target)
        print(f"{target.relative_to(ROOT)}  {target.stat().st_size // 1024} KiB")

    lines = [
        "// Generated by scripts/subset-font.py from src/ui/icon-names.json. Do not edit.",
        "export const ICONS = {",
    ]
    esc = "\\" + "u"
    lines += [f"  {key}: '{esc}{{{cp:X}}}'," for key, cp in icons.items()]
    lines += ["} as const;", "", "export type IconName = keyof typeof ICONS;", ""]
    (ROOT / "src/ui/icons.generated.ts").write_text("\n".join(lines), "utf-8")
    print(f"src/ui/icons.generated.ts  {len(icons)} icons")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
